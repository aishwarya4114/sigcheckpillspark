"""Export the reference data as Markdown for the PRISM Knowledge Base (it accepts .txt/.md/.pdf only).

    python -m faxfill.ref.export_kb      # writes faxfill/ref/kb/{drugs,prescribers,high_alert}.md

Generated from drugs.json / prescribers.csv / high_alert.json, so the KB copy always matches what the
verifier uses. Source labels are kept, including "manual, unverified".
"""
import csv
import json
from pathlib import Path

HERE = Path(__file__).parent
KB = HERE / "kb"
STAMP = "Demo reference data for a hackathon review workflow. NOT for clinical use."


def num(v):
    return f"{v:g}" if isinstance(v, (int, float)) else str(v)


def drugs_md():
    data = json.load(open(HERE / "drugs.json"))
    out = ["# SigCheck drug reference (41 drugs)", "", STAMP, "",
           "Sources: **rxnorm** = NLM RxNav (SCD concepts, oral tablet/capsule/solution); **openfda** = openFDA NDC "
           "`dea_schedule`; **manual, unverified** = hand-entered, not checked against a source.", "",
           "| Drug | RxCUI by strength | Strengths (printed form) | Oral forms in RxNorm | DEA schedule | Look-alike partners | Usual max daily dose | Allergy classes | Sources |",
           "|---|---|---|---|---|---|---|---|---|"]
    for d in data["drugs"]:
        unit = d["unit"]["value"]
        rxcui = d["rxcui"]["value"]
        rxcui_txt = "; ".join(f"{k} {unit} = {v}" for k, v in rxcui.items()) or "none found"
        strengths = ", ".join(num(s) for s in d["strengths"]["value"]) + f" {unit} ({d['form']['value']})"
        nice = {"tablet": "tablet", "tablet_er": "extended-release tablet", "tablet_dr": "delayed-release tablet",
                "tablet_odt": "orally disintegrating tablet", "tablet_chewable": "chewable tablet", "capsule": "capsule",
                "capsule_er": "extended-release capsule", "capsule_dr": "delayed-release capsule", "solution": "oral solution"}
        forms = ", ".join(nice.get(k, k) for k in sorted(d["strengths_by_form"]["value"])) or "—"
        sched = d["schedule"]["value"] or "not controlled (none listed)"
        lasa = ", ".join(d["lasa"]["value"]) or "—"
        maxd = f"{num(d['max_daily']['value'])} {d['max_daily']['unit']}/" + ("week" if d.get("frequency_rule") else "day")
        if d.get("frequency_rule"):
            maxd += " (dosed once WEEKLY)"
        classes = ", ".join(d["classes"]["value"]) or "—"
        src = (f"strengths: {d['strengths']['source']}; unit: {d['unit']['source']}; RxCUI: {d['rxcui']['source']}; forms: {d['strengths_by_form']['source']}; "
               f"DEA schedule: {d['schedule']['source']}; look-alikes: {d['lasa']['source']}; max dose: {d['max_daily']['source']}; "
               f"allergy classes: {d['classes']['source']}"
               + (f"; weekly rule: {d['frequency_rule']['source']}" if d.get("frequency_rule") else ""))
        out.append(f"| {d['name']} | {rxcui_txt} | {strengths} | {forms} | {sched} | {lasa} | {maxd} | {classes} | {src} |")
    return "\n".join(out) + "\n"


def prescribers_md():
    rows = list(csv.DictReader(open(HERE / "prescribers.csv")))
    out = ["# SigCheck prescriber directory (15 fictional prescribers)", "", STAMP, "",
           "All people are fictional. Every NPI passes the Luhn check (80840 prefix) and returned 0 results in the public "
           "CMS NPI Registry on 2026-10-10, so none belongs to a real provider. DEA numbers pass the DEA check digit; "
           "there is no public DEA lookup, so they are only checksum-valid. Source: fictional, generated by "
           "faxfill/ref/make_people.py.", "",
           "| Prescriber | Credential | Clinic | Address | Phone | Fax | NPI | DEA |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['first_name']} {r['last_name']} | {r['credential']} | {r['clinic']} | {r['address']} | "
                   f"{r['phone']} | {r['fax']} | {r['npi']} | {r['dea'] or 'none (does not prescribe controlled substances)'} |")
    return "\n".join(out) + "\n"


def high_alert_md():
    h = json.load(open(HERE / "high_alert.json"))
    out = ["# SigCheck high-alert drugs", "", STAMP, "", f"Source: **{h['_meta']['source']}**. {h['_meta']['note']}", "",
           "| Drug | ISMP community high-alert category | Source |", "|---|---|---|"]
    for d in h["drugs"]:
        out.append(f"| {d['name']} | {d['category']} | {h['_meta']['source']} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    KB.mkdir(exist_ok=True)
    for name, fn in (("drugs.md", drugs_md), ("prescribers.md", prescribers_md), ("high_alert.md", high_alert_md)):
        (KB / name).write_text(fn())
        print(name, (KB / name).stat().st_size, "bytes")
